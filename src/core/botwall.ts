// Recognises bot-protection challenge pages. A recognised wall is reported as `blocked`; the
// app never tries to get past it.

const STRONG: [string, RegExp][] = [
  ['cloudflare', /just a moment\.\.\.|cf-chl|challenge-platform|_cf_chl|cf-browser-verification|attention required! \| cloudflare/],
  ['datadome', /captcha-delivery\.com|datadome/],
  ['akamai', /errors\.edgesuite\.net|reference&#32;&#35;|ak_bmsc/],
  ['perimeterx', /perimeterx|px-captcha|_pxhd|human verification/],
  ['imperva', /incapsula|_incap_|imperva/],
  ['cloudfront', /the request could not be satisfied|generated by cloudfront/],
  ['generic_challenge', /vyžaduje sa overenie|vyzaduje sa overenie|bot detected|access denied|pardon our interruption|are you a robot|verify you are human|ověřte, že jste člověk|sicherheitsabfrage|robot check|bitte bestätigen sie/],
];

export interface BotWall {
  detected: boolean;
  vendor: string | null;
}

export function detectBotWall(status: number | null, headers: Headers | null, text: string): BotWall {
  const low = (text ?? '').slice(0, 200_000).toLowerCase();
  const h = (k: string) => headers?.get(k)?.toLowerCase() ?? '';
  let vendor: string | null = null;
  if (h('cf-mitigated') === 'challenge') vendor = 'cloudflare';
  if (!vendor && (headers?.has('x-datadome') || h('set-cookie').includes('datadome'))) vendor = 'datadome';
  const small = (text ?? '').length < 60_000;
  if (!vendor) {
    for (const [name, re] of STRONG) {
      if (re.test(low) && (small || name === 'cloudflare' || name === 'datadome')) {
        vendor = name;
        break;
      }
    }
  }
  if (!vendor && small) {
    const visible = low.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>|<[^>]+>/g, ' ');
    if (/captcha|recaptcha|hcaptcha/.test(visible)) vendor = 'captcha';
  }
  const blockedStatus = status === 401 || status === 403 || status === 429 || status === 503;
  let detected = Boolean(vendor) && (blockedStatus || small);
  if (blockedStatus && !vendor) {
    vendor = h('server').startsWith('cloudflare') ? 'cloudflare' : `http_${status}`;
    detected = true;
  }
  return { detected, vendor: detected ? vendor : null };
}
